using System;
using System.IO;
using System.Linq;
using System.Collections.Generic;
namespace WeChatPet.Runtime {
 public static class MemoryUpdateTests {
  public static void Run(Action<string,bool> check) {
   string dir=Path.Combine(AppDomain.CurrentDomain.BaseDirectory,"memory-updates-"+Guid.NewGuid().ToString("N"));Directory.CreateDirectory(dir);
   try {
    var identity=new MemoryIdentity(dir);var store=new MemoryStore(dir);long now=DateTime.UtcNow.Ticks;int index=0;uint message=0;
    Func<ChatSnapshot> fresh=()=>new ChatSnapshot{Available=true,AtEnd=true,Contact="测试好友",AccountId=identity.Account("a"),FriendId=identity.Friend("a",(++index).ToString()),Messages=new List<ChatMessage>()};
    Func<string,long,string,ChatMessage> make=(text,time,role)=>new ChatMessage{Type=1,LocalId=++message,MemoryKey=identity.Message("a","f",message.ToString()),Text=text,CreatedTicks=time,Role=role};
    Action<ChatSnapshot,string,long> add=(s,text,time)=>{s.Messages.Add(make(text,time,"peer"));store.Observe(s,now);};
    var chat=fresh();add(chat,"我不吃香菜",now-100);add(chat,"我现在吃香菜了",now-50);
    check("改口只保留最新明确饮食偏好",store.Context(chat,now).Contains("我现在吃香菜了")&&!store.Context(chat,now).Contains("我不吃香菜"));
    add(chat,"我现在吃香菜了！",now-10);
    check("同义标点重复只保留最新来源",store.Current(chat).Items.Count(i=>i.Kind=="stated")==1&&store.Current(chat).Items[0].SourceTicks==now-10);
    add(chat,"我不吃香菜",now-200);
    check("迟到旧消息不覆盖新偏好",!store.Context(chat,now).Contains("我不吃香菜"));
    store.Current(chat).Seen.Clear();store.Current(chat).Items.Clear();store.Observe(chat,now);
    check("重读与容量清理后更新水位阻止旧偏好复活",store.Current(chat).Items.Count==1&&store.Current(chat).Items[0].SourceTicks==now-10);
    var same=fresh();add(same,"我喜欢咖啡",now-50);add(same,"我不喜欢咖啡",now-50);
    check("同秒消息按稳定本地顺序更新",!store.Context(same,now).Contains("：我喜欢咖啡")&&store.Context(same,now).Contains("我不喜欢咖啡"));
    var scope=fresh();add(scope,"我不吃香菜",now-100);add(scope,"我喜欢跑步",now-90);add(scope,"我现在吃香菜了",now-70);
    scope.Messages.Add(make("我不吃香菜",now-10,"self"));store.Observe(scope,now);
    check("本人表达不覆盖好友且不同主题互不影响",store.Current(scope).Items.Count(i=>i.Kind=="stated")==2&&store.Context(scope,now).Contains("我喜欢跑步")&&store.Context(scope,now).Contains("我现在吃香菜了"));
    var selfEntry=store.Current(scope).Items.Single(i=>i.SourceRole=="self");
    store.Put(store.Current(scope),selfEntry,"我不吃香菜！",true,now+1);
    string selfEdited=store.Context(scope,now+1);
    check("编辑本人摘录保留self主体且不覆盖好友的相反偏好",selfEdited.Contains("关于本人（self）的信息，由用户确认")&&selfEdited.Contains("我不吃香菜！")&&selfEdited.Contains("当前好友（peer）曾自述")&&selfEdited.Contains("我现在吃香菜了")&&!store.Current(scope).Items.Single(i=>i.SourceRole=="peer"&&i.Text=="我现在吃香菜了").Superseded);
    var legacyNote=new MemoryItem{Id="legacy-unassigned",Text="我不吃香菜",Kind="note",Manual=true,SourceTicks=now,UpdatedTicks=now+2};store.Current(scope).Items.Add(legacyNote);
    check("无主体来源的旧手动备注不参与好友冲突或传给模型",!store.Context(scope,now+2).Contains("：我不吃香菜\r\n")&&store.Context(scope,now+2).Contains("我现在吃香菜了")&&!legacyNote.Superseded);
    store.Put(store.Current(scope),legacyNote,"饮食偏好：不吃香菜",true,now+3);
    check("旧手动备注经关于好友编辑确认后才归为peer",MemoryStore.Subject(legacyNote)=="peer"&&store.Context(scope,now+3).Contains("关于当前好友（peer）的信息，由用户确认")&&!store.Context(scope,now+3).Contains("我现在吃香菜了"));
    var legacySelf=fresh();add(legacySelf,"我现在吃香菜了",now-10);var legacyFriend=store.Current(legacySelf);
    var wrongSelf=new MemoryItem{Id="old-edited-self",Text="我不吃香菜",Kind="recent",Manual=true,SourceRole="self",SourceTicks=now-100,UpdatedTicks=now};legacyFriend.Items.Add(wrongSelf);legacyFriend.PreferenceHeads["吃:香菜"]=new PreferenceHead{Ticks=now,Order=Int64.MaxValue};
    check("旧版本由self编辑污染的偏好水位不再压制peer",store.Context(legacySelf,now).Contains("我现在吃香菜了")&&MemoryStore.Subject(wrongSelf)=="self");
    check("好友间更新隔离",!store.Context(same,now).Contains("香菜"));
    var fixedChat=fresh();add(fixedChat,"你好",now-1000);var f=store.Current(fixedChat);
    store.Put(f,null,"饮食偏好：不吃香菜",true,now-500);var old=f.Items.Last();add(fixedChat,"我现在吃香菜了",now-100);
    check("新明确表达使旧固定偏好停止推荐但保留可见记录",old.Superseded&&f.Items.Contains(old)&&!store.Context(fixedChat,now).Contains("不吃香菜"));
    string expired=store.Context(fixedChat,now+TimeSpan.TicksPerDay*31);
    check("新偏好过期后旧固定记录不会重新生效",!expired.Contains("香菜"));
    store.Put(f,old,"饮食偏好：不吃香菜",true,now+TimeSpan.TicksPerDay*32);
    check("用户再次明确编辑可恢复记录",!old.Superseded&&store.Context(fixedChat,now+TimeSpan.TicksPerDay*32).Contains("不吃香菜"));
    var confirmation=fresh();add(confirmation,"你好",now-1000);var confirmed=store.Current(confirmation);
    store.Put(confirmed,null,"我不吃香菜",true,now-900);var retained=confirmed.Items.Single(i=>i.Manual);
    add(confirmation,"我不吃香菜！",now-100);
    check("相同的新自述确认固定记忆而不降级成自动摘录",!retained.Superseded&&confirmed.Items.Count(i=>!i.Superseded&&i.Text.Contains("香菜"))==1&&store.Context(confirmation,now).Contains("我不吃香菜"));
    store.Save();var reopenedConfirmation=new MemoryStore(dir);
    check("重启与自动记忆过期不丢失被重复确认的固定记忆",reopenedConfirmation.Context(confirmation,now+TimeSpan.TicksPerDay*31).Contains("我不吃香菜"));
    add(confirmation,"我吃香菜",now-500);
    check("确认水位阻止迟到旧反例覆盖固定记忆",!retained.Superseded&&store.Context(confirmation,now).Contains("我不吃香菜"));
    add(confirmation,"我现在吃香菜了",now-50);
    check("固定记忆经重复确认后仍服从更新的明确改口",retained.Superseded&&!store.Context(confirmation,now).Contains("我不吃香菜")&&store.Context(confirmation,now).Contains("我现在吃香菜了"));
    var tiedConfirmation=fresh();add(tiedConfirmation,"你好",now-1000);var tiedFriend=store.Current(tiedConfirmation);
    store.Put(tiedFriend,null,"我不吃香菜",true,now-900);var tiedPinned=tiedFriend.Items.Single(i=>i.Manual);
    var sameTimeConfirmation=make("我不吃香菜",now-100,"peer");sameTimeConfirmation.LocalId=0;tiedConfirmation.Messages.Add(sameTimeConfirmation);store.Observe(tiedConfirmation,now);
    check("未知顺序的相同自述去重后仍保留固定偏好",!tiedPinned.Superseded&&tiedFriend.Items.Count(i=>!i.Superseded&&i.Text.Contains("香菜"))==1);
    store.Save();var reopenedTie=new MemoryStore(dir);
    var sameTimeConflict=make("我吃香菜",now-100,"peer");sameTimeConflict.LocalId=0;tiedConfirmation.Messages.Add(sameTimeConflict);reopenedTie.Observe(tiedConfirmation,now);
    check("重启后等时间未知顺序的反例仍与已去重确认形成歧义",reopenedTie.Current(tiedConfirmation).PreferenceHeads["吃:香菜"].Ambiguous&&!reopenedTie.Context(tiedConfirmation,now).Contains("香菜"));
    reopenedTie.Save();reopenedTie=new MemoryStore(dir);var reopenedTiedFriend=reopenedTie.Current(tiedConfirmation);
    check("去重确认产生的歧义跨重启保持且不进入上下文",reopenedTiedFriend.PreferenceHeads["吃:香菜"].Ambiguous&&!reopenedTie.Context(tiedConfirmation,now).Contains("香菜"));
    reopenedTiedFriend.Seen.Clear();tiedConfirmation.Messages.Remove(sameTimeConflict);reopenedTie.Observe(tiedConfirmation,now);
    check("歧义后只重读先前确认也不能恢复固定偏好",!reopenedTie.Context(tiedConfirmation,now).Contains("香菜"));
    tiedConfirmation.Messages.Add(make("我现在吃香菜了",now+1,"peer"));reopenedTie.Observe(tiedConfirmation,now+1);
    check("真正较新的明确偏好清除旧指纹歧义并替代固定项",!reopenedTiedFriend.PreferenceHeads["吃:香菜"].Ambiguous&&reopenedTie.Context(tiedConfirmation,now+1).Contains("我现在吃香菜了")&&!reopenedTie.Context(tiedConfirmation,now+1).Contains("我不吃香菜"));
    var dislike=fresh();add(dislike,"我喜欢咖啡",now-1000);add(dislike,"我讨厌咖啡",now-100);
    string dislikeLater=store.Context(dislike,now+TimeSpan.TicksPerDay*8);
    check("明确讨厌与喜欢使用同一主题且不会七天后复活旧喜欢",dislikeLater.Contains("我讨厌咖啡")&&!dislikeLater.Contains("我喜欢咖啡"));
    foreach(string text in new[]{"我讨厌咖啡吗？","我今天讨厌咖啡","我可能讨厌咖啡","他说我讨厌咖啡","我讨厌咖啡哈哈","我讨厌咖啡和茶"})check("讨厌规则保留不确定或复合表达边界："+text,PreferenceRules.Key(text,false)==null);
    var uncertain=fresh();add(uncertain,"我不吃香菜",now-1000);
    foreach(string text in new[]{"我今天吃香菜","我现在吃香菜吗？","我可能吃香菜","我吃香菜哈哈","我喜欢香菜但过敏","我不是不吃香菜","我不吃香菜和葱","我不吃香菜\n他说的","我以前吃香菜"})add(uncertain,text,now-10);
    check("临时问句玩笑转述和复合语义不更新偏好",store.Current(uncertain).Items.Count(i=>i.Kind=="stated")==1&&store.Context(uncertain,now).Contains("我不吃香菜"));
    check("过去现在明确改口支持省略同一对象",PreferenceRules.Key("我以前不吃香菜，现在吃了",false)=="吃:香菜");
    check("不同偏好维度不强行冲突",PreferenceRules.Key("我喜欢香菜",false)!=PreferenceRules.Key("我不吃香菜",false));
    check("称呼更新归于同一项",PreferenceRules.Key("以后叫我小美",false)==PreferenceRules.Key("以后叫我小李",false));
    var recent=fresh();add(recent,"你好！",now-100);add(recent,"你好。",now-50);
    check("重复近期聊天不会挤占记忆",store.Current(recent).Items.Count==1&&store.Current(recent).Items[0].SourceTicks==now-50);
    check("七天旧摘录不用于推荐",!store.Context(recent,now+TimeSpan.TicksPerDay*8).Contains("你好"));
    store.Save();store=new MemoryStore(dir);
    check("重启保留更新水位和有效结果",store.Error==null&&store.Context(chat,now).Contains("我现在吃香菜了")&&!store.Context(chat,now).Contains("我不吃香菜"));
    check("重启保留被替代记录状态",store.Current(fixedChat).Items.Any(i=>i.Manual));
    var tied=fresh();var yes=make("我吃香菜",now,"peer");var no=make("我不吃香菜",now,"peer");yes.LocalId=no.LocalId=0;tied.Messages.Add(yes);tied.Messages.Add(no);store.Observe(tied,now);
    check("旧格式同秒冲突且无顺序时不猜测",!store.Context(tied,now).Contains("香菜"));
    store.Current(tied).Seen.Clear();tied.Messages.Remove(yes);store.Observe(tied,now);
    check("顺序未知的冲突不会因单条重读而复活",!store.Context(tied,now).Contains("香菜"));
    add(tied,"我现在吃香菜了",now+1);
    check("更新明确时间可解除旧冲突",store.Context(tied,now+1).Contains("我现在吃香菜了"));
   }finally{foreach(string path in Directory.GetFiles(dir))File.Delete(path);Directory.Delete(dir);}
  }
 }
}
